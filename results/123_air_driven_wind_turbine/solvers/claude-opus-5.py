"""Two-way coupled air-driven wind turbine (self-implemented, NumPy/SciPy only).

Air
---
Incompressible Navier-Stokes on the frozen ``112 x 64 x 60`` voxel grid, advanced with
stable semi-Lagrangian advection plus an exact spectral pressure projection: DCT-IV
along x (Neumann inlet at ``x_min``, Dirichlet outlet at ``x_max``) and DCT-II along
y and z (Neumann).  The ground is no-slip, the frozen tower and nacelle cylinders are
imposed by direct forcing, and the inlet follows the scene's ramped control.

Rotor
-----
A rigid body on the frozen revolute axle (fixed position and direction, free angle).
Blade-element / actuator-line aerodynamics evaluate lift and drag from the *resolved*
local air velocity at each blade station; the equal and opposite reaction is deposited
back into the air.  The rotor is therefore driven by the fluid it disturbs, and the
wake (including its swirl) is generated by the rotor.  The axle contributes the frozen
viscous plus regularized-Coulomb resisting torque, which limits spin-up to a steady
rotation rate.  No angular speed is ever prescribed.

Smoke
-----
Three passive dimensionless tracers emitted at the frozen rotor-local blade-tip points,
painted along the swept arc each substep and advected by the simulated velocity field.
"""
from __future__ import annotations

import numpy as np
from scipy import fft as sfft
from scipy.ndimage import map_coordinates

from worldsolver.contracts import StateFrame

GRAVITY = np.array([0.0, 0.0, -9.81])
SOUND_SPEED = 340.0
MAX_SUBSTEP = 0.01
N_BLADES = 3
N_ELEMENTS = 12
N_SUBANGLE = 3
N_EMIT_SUB = 4
STALL_ANGLE = np.deg2rad(14.0)
STALL_BLEND = np.deg2rad(12.0)
LIFT_SLOPE = 2.0 * np.pi * 0.9
PROFILE_DRAG = 0.02
SEPARATED_DRAG = 1.9
DESIGN_TSR = 3.5
DESIGN_AOA = np.deg2rad(7.0)
CHORD_ROOT = 0.44
CHORD_TIP = 0.16
BLADE_ROOT = 0.30
BLADE_TIP = 2.05
SMOKE_AMPLITUDE = 0.6
SMOKE_CEILING = 1.0
KERNEL_HALF = 3


def _quaternion_matrix(q) -> np.ndarray:
    """Rotation matrix of an xyzw quaternion."""
    x, y, z, w = (float(v) for v in q)
    n = np.sqrt(x * x + y * y + z * z + w * w)
    if n < 1e-12:
        return np.eye(3)
    x, y, z, w = x / n, y / n, z / n, w / n
    return np.array(
        [
            [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
            [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
            [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
        ]
    )


def _airfoil_coefficients(alpha):
    """Thin-airfoil lift with a smooth blend to separated flat-plate behaviour."""
    attached = LIFT_SLOPE * alpha
    plate = 2.0 * np.sin(alpha) * np.cos(alpha)
    blend = np.clip((np.abs(alpha) - STALL_ANGLE) / STALL_BLEND, 0.0, 1.0)
    lift = (1.0 - blend) * attached + blend * plate
    drag = PROFILE_DRAG + SEPARATED_DRAG * np.sin(alpha) ** 2
    return lift, drag


def _mesh_inertia(path: str, mass: float):
    """Volume, centroid and inertia about the mesh origin from a triangle-soup asset.

    Component-wise tetrahedral quadrature with absolute volumes, so inconsistent
    face winding in the frozen asset cannot corrupt the mass properties.
    """
    vertices: list[list[float]] = []
    faces: list[list[int]] = []
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "v":
                vertices.append([float(v) for v in parts[1:4]])
            elif parts[0] == "f":
                idx = [int(t.split("/")[0]) - 1 for t in parts[1:]]
                for k in range(1, len(idx) - 1):
                    faces.append([idx[0], idx[k], idx[k + 1]])
    points = np.asarray(vertices, dtype=float)
    triangles = np.asarray(faces, dtype=int)
    if points.size == 0 or triangles.size == 0:
        raise ValueError("empty rotor mesh")

    # Group vertices into connected components so each closed sub-solid is integrated
    # from its own centroid.
    label = -np.ones(len(points), dtype=int)
    adjacency: list[set[int]] = [set() for _ in range(len(points))]
    for tri in triangles:
        for a in tri:
            adjacency[a].update(int(b) for b in tri)
    current = 0
    for start in range(len(points)):
        if label[start] >= 0:
            continue
        stack = [start]
        label[start] = current
        while stack:
            node = stack.pop()
            for nb in adjacency[node]:
                if label[nb] < 0:
                    label[nb] = current
                    stack.append(nb)
        current += 1

    a_q = 0.5854101966249685
    b_q = 0.1381966011250105
    bary = np.array(
        [
            [a_q, b_q, b_q, b_q],
            [b_q, a_q, b_q, b_q],
            [b_q, b_q, a_q, b_q],
            [b_q, b_q, b_q, a_q],
        ]
    )
    volume = 0.0
    moment1 = np.zeros(3)
    second = np.zeros((3, 3))
    for component in range(current):
        members = np.flatnonzero(label == component)
        centroid = points[members].mean(axis=0)
        member_set = set(int(m) for m in members)
        for tri in triangles:
            if not member_set.issuperset(int(t) for t in tri):
                continue
            tet = np.array([centroid, points[tri[0]], points[tri[1]], points[tri[2]]])
            jac = np.array([tet[1] - tet[0], tet[2] - tet[0], tet[3] - tet[0]])
            vol = abs(float(np.linalg.det(jac))) / 6.0
            if vol <= 0.0:
                continue
            quad = bary @ tet
            volume += vol
            moment1 += vol * quad.mean(axis=0)
            second += vol * (quad.T @ quad) / 4.0
    if volume <= 1e-9:
        raise ValueError("degenerate rotor mesh volume")
    density = mass / volume
    second = second * density
    inertia = np.trace(second) * np.eye(3) - second
    return volume, moment1 / volume, inertia


class BenchmarkSolver:
    """Self-implemented two-way fluid/rigid solver for the air-driven wind turbine."""

    def initialize(self, scene, seed: int) -> None:
        self.scene = scene
        config = scene.config
        self.config = config
        self.rng = np.random.default_rng(int(seed))

        domain = config["domain"]
        self.low = np.asarray(domain["bounds_min"], dtype=float)
        self.high = np.asarray(domain["bounds_max"], dtype=float)
        self.shape = tuple(int(v) for v in domain["reference_grid"])
        self.dx = (self.high - self.low) / np.asarray(self.shape, dtype=float)
        self.cell_volume = float(np.prod(self.dx))

        air = config["air"]
        self.air_density = float(air["density"])
        self.inlet_speed = float(np.linalg.norm(air["inlet"]["velocity"]))

        nx, ny, nz = self.shape
        self.u = np.zeros((nx, ny, nz), dtype=np.float32)
        self.v = np.zeros((nx, ny, nz), dtype=np.float32)
        self.w = np.zeros((nx, ny, nz), dtype=np.float32)
        self.u[:] = np.asarray(air["initial_velocity"], dtype=float)[0]
        self.v[:] = np.asarray(air["initial_velocity"], dtype=float)[1]
        self.w[:] = np.asarray(air["initial_velocity"], dtype=float)[2]
        self.pressure = np.zeros((nx, ny, nz), dtype=np.float32)
        self.smoke_names = list(config["smoke"]["channels"])
        self.smoke = [np.zeros((nx, ny, nz), dtype=np.float32) for _ in self.smoke_names]

        # Cell-centre coordinates and index grids reused every advection step.
        self.xc = self.low[0] + (np.arange(nx) + 0.5) * self.dx[0]
        self.yc = self.low[1] + (np.arange(ny) + 0.5) * self.dx[1]
        self.zc = self.low[2] + (np.arange(nz) + 0.5) * self.dx[2]
        self.ix = np.arange(nx, dtype=np.float32).reshape(nx, 1, 1)
        self.iy = np.arange(ny, dtype=np.float32).reshape(1, ny, 1)
        self.iz = np.arange(nz, dtype=np.float32).reshape(1, 1, nz)

        self._build_solid_mask()
        self._build_rotor()
        self._build_poisson()
        self._build_boundary_samples()

        turbine = config["turbine"]
        self.theta = float(turbine["initial_angle"])
        self.omega = float(turbine["initial_angular_velocity"])
        friction = turbine["axle_friction"]
        self.visc_friction = float(friction["viscous_coefficient"])
        self.coulomb_friction = float(friction["coulomb_torque"])
        self.friction_eps = float(friction["regularization_speed"])
        self.body_id = int(turbine["rotor_body_id"])

        smoke_cfg = config["smoke"]
        self.emit_start = float(smoke_cfg["emission_start"])
        self.emit_end = float(smoke_cfg["emission_end"])
        self.emit_rate = float(smoke_cfg["source_rate_each"])
        self.source_radius = float(smoke_cfg["source_radius"])
        self.tip_local = np.asarray(smoke_cfg["rotor_local_tip_positions"], dtype=float)

        self.time = 0.0
        self.step_count = 0
        self.angular_impulse = np.zeros(3)
        self.max_omega = 0.0
        # Rest state at t = 0: no airflow, no aerodynamic load, no friction torque.
        rest_positions, _, _ = self._blade_loads(self.theta, self.omega)
        self._store_terms(rest_positions, np.zeros((N_BLADES * N_ELEMENTS, 3)), 0.0, 0.0, 0.0)

    def _build_solid_mask(self) -> None:
        """Direct-forcing mask for the frozen static tower and nacelle cylinders."""
        nx, ny, nz = self.shape
        mask = np.zeros((nx, ny, nz), dtype=bool)
        dxg = (self.xc - 0.0).reshape(nx, 1, 1)
        geometry = self.config.get("scene_geometry", {}) or {}
        for item in geometry.get("objects", []):
            if item.get("motion") != "static":
                continue
            spec = item.get("geometry", {})
            if spec.get("type") != "cylinder":
                continue
            transform = item.get("transform", {}) or {}
            centre = np.asarray(transform.get("translation", [0.0, 0.0, 0.0]), dtype=float)
            quat = transform.get("rotation_xyzw", [0.0, 0.0, 0.0, 1.0])
            axis = _quaternion_matrix(quat) @ np.array([0.0, 0.0, 1.0])
            axis = axis / max(float(np.linalg.norm(axis)), 1e-12)
            radius = float(spec["radius"])
            half = 0.5 * float(spec["height"])
            ox = (self.xc - centre[0]).reshape(nx, 1, 1)
            oy = (self.yc - centre[1]).reshape(1, ny, 1)
            oz = (self.zc - centre[2]).reshape(1, 1, nz)
            along = ox * axis[0] + oy * axis[1] + oz * axis[2]
            dist2 = ox * ox + oy * oy + oz * oz - along * along
            mask |= (np.abs(along) <= half) & (dist2 <= radius * radius)
        del dxg
        self.solid = mask

    def _build_rotor(self) -> None:
        turbine = self.config["turbine"]
        self.hub = np.asarray(turbine["hub_center"], dtype=float)
        axis = np.asarray(turbine["axle_axis"], dtype=float)
        self.axis = axis / max(float(np.linalg.norm(axis)), 1e-12)
        self.rotor_radius = float(turbine["rotor_radius"])
        self.rotor_mass = float(turbine["mass"])

        # Orthonormal rotor-plane basis: e_r(psi) = cos(psi) e1 + sin(psi) e2.
        reference = np.array([0.0, 0.0, 1.0])
        if abs(float(np.dot(reference, self.axis))) > 0.9:
            reference = np.array([0.0, 1.0, 0.0])
        e1 = reference - np.dot(reference, self.axis) * self.axis
        e1 /= max(float(np.linalg.norm(e1)), 1e-12)
        e2 = np.cross(self.axis, e1)
        self.e1 = e1
        self.e2 = e2

        inertia_axial = 0.23 * self.rotor_mass * self.rotor_radius ** 2
        inertia_transverse = 0.5 * inertia_axial
        asset = None
        for item in (self.config.get("scene_geometry", {}) or {}).get("objects", []):
            if item.get("id") == "rotor":
                asset = (item.get("geometry", {}) or {}).get("asset")
        if asset:
            try:
                _, _, tensor = _mesh_inertia(str(asset), self.rotor_mass)
                axial = float(self.axis @ tensor @ self.axis)
                transverse = 0.5 * (float(np.trace(tensor)) - axial)
                if np.isfinite(axial) and 1.0 < axial < 400.0:
                    inertia_axial = axial
                    inertia_transverse = max(transverse, 0.1 * axial)
            except Exception:
                pass
        self.inertia_axial = float(inertia_axial)
        self.inertia_transverse = float(inertia_transverse)
        # The revolute axle fixes the centre of mass on the axle line, so the balanced
        # rotor centre of mass stays at rest and gravity exerts no axial torque.
        self.com = self.hub.copy()
        # Transversely isotropic about the frozen axle: constant in world coordinates.
        self.inertia_world = (
            self.inertia_axial * np.outer(self.axis, self.axis)
            + self.inertia_transverse * (np.eye(3) - np.outer(self.axis, self.axis))
        )

        # Blade-element discretisation (chord taper read off the frozen blade mesh).
        radii = np.linspace(BLADE_ROOT, BLADE_TIP, N_ELEMENTS)
        self.elem_radius = radii
        self.elem_span = (BLADE_TIP - BLADE_ROOT) / (N_ELEMENTS - 1)
        self.elem_chord = CHORD_ROOT + (CHORD_TIP - CHORD_ROOT) * (
            (radii - BLADE_ROOT) / (BLADE_TIP - BLADE_ROOT)
        )
        design_omega = DESIGN_TSR * self.inlet_speed / self.rotor_radius
        self.elem_twist = np.arctan2(self.inlet_speed, design_omega * radii) - DESIGN_AOA
        self.blade_offsets = 2.0 * np.pi * np.arange(N_BLADES) / N_BLADES

    def _build_poisson(self) -> None:
        """Eigenvalues of the 7-point Laplacian in the DCT-IV(x)/DCT-II(y,z) basis."""
        nx, ny, nz = self.shape
        kx = (np.arange(nx) + 0.5) * np.pi / (2.0 * nx)
        ky = np.arange(ny) * np.pi / (2.0 * ny)
        kz = np.arange(nz) * np.pi / (2.0 * nz)
        lam_x = -4.0 * np.sin(kx) ** 2 / self.dx[0] ** 2
        lam_y = -4.0 * np.sin(ky) ** 2 / self.dx[1] ** 2
        lam_z = -4.0 * np.sin(kz) ** 2 / self.dx[2] ** 2
        denom = (
            lam_x.reshape(nx, 1, 1) + lam_y.reshape(1, ny, 1) + lam_z.reshape(1, 1, nz)
        )
        # DCT-IV keeps every x eigenvalue strictly negative, so there is no null mode.
        denom[np.abs(denom) < 1e-12] = -1e-12
        self.poisson_denominator = denom.astype(np.float32)

    def _build_boundary_samples(self) -> None:
        """Fixed wall/inlet sample set with unit outward normals."""
        nx, ny, nz = self.shape
        indices: list[tuple[int, int, int]] = []
        normals: list[list[float]] = []
        kinds: list[int] = []  # 0 = inlet, 1 = static wall
        for j in range(0, ny, 6):
            for k in range(0, nz, 6):
                indices.append((0, j, k))
                normals.append([-1.0, 0.0, 0.0])
                kinds.append(0)
        for i in range(0, nx, 10):
            for j in range(0, ny, 8):
                indices.append((i, j, 0))
                normals.append([0.0, 0.0, 1.0])
                kinds.append(1)
        solid_cells = np.argwhere(self.solid)
        if len(solid_cells):
            stride = max(1, len(solid_cells) // 120)
            for cell in solid_cells[::stride][:120]:
                i, j, k = (int(cell[0]), int(cell[1]), int(cell[2]))
                radial = np.array([0.0, self.yc[j], 0.0])
                if float(np.linalg.norm(radial)) < 1e-9:
                    radial = np.array([0.0, 1.0, 0.0])
                radial = radial / float(np.linalg.norm(radial))
                indices.append((i, j, k))
                normals.append(list(radial))
                kinds.append(1)
        arr = np.asarray(indices, dtype=int)
        self.boundary_index = (arr[:, 0], arr[:, 1], arr[:, 2])
        self.boundary_normal = np.asarray(normals, dtype=float)
        self.boundary_kind = np.asarray(kinds, dtype=int)

    def _apply_boundaries(self, time: float) -> None:
        """Inlet control, no-slip ground and direct forcing inside the static solids."""
        inlet = np.asarray(self.scene.inlet_velocity(time), dtype=float)
        self.u[0, :, :] = inlet[0]
        self.v[0, :, :] = inlet[1]
        self.w[0, :, :] = inlet[2]
        self.u[:, :, 0] = 0.0
        self.v[:, :, 0] = 0.0
        self.w[:, :, 0] = 0.0
        if self.solid.any():
            self.u[self.solid] = 0.0
            self.v[self.solid] = 0.0
            self.w[self.solid] = 0.0

    def _trace(self, dt: float):
        """Backward characteristic feet in index space (clamped at open boundaries)."""
        nx, ny, nz = self.shape
        cx = np.clip(self.ix - (dt / self.dx[0]) * self.u, 0.0, nx - 1.0)
        cy = np.clip(self.iy - (dt / self.dx[1]) * self.v, 0.0, ny - 1.0)
        cz = np.clip(self.iz - (dt / self.dx[2]) * self.w, 0.0, nz - 1.0)
        return np.stack((cx, cy, cz), axis=0)

    @staticmethod
    def _sample(field, coords):
        return map_coordinates(field, coords, order=1, mode="nearest", prefilter=False)

    def _advect_velocity(self, dt: float) -> None:
        coords = self._trace(dt)
        u_new = self._sample(self.u, coords)
        v_new = self._sample(self.v, coords)
        w_new = self._sample(self.w, coords)
        self.u, self.v, self.w = u_new, v_new, w_new

    def _advect_smoke(self, dt: float) -> None:
        coords = self._trace(dt)
        for index, field in enumerate(self.smoke):
            self.smoke[index] = self._sample(field, coords)

    def _project(self, dt: float, time: float) -> None:
        """Exact spectral pressure projection of the collocated velocity field."""
        nx, ny, nz = self.shape
        inlet = np.asarray(self.scene.inlet_velocity(time), dtype=float)

        # Ghost layers: prescribed inlet, zero-gradient open faces, no-slip ground.
        u_pad = np.empty((nx + 2, ny, nz), dtype=np.float32)
        u_pad[1:-1] = self.u
        u_pad[0] = inlet[0]
        u_pad[-1] = self.u[-1]
        v_pad = np.empty((nx, ny + 2, nz), dtype=np.float32)
        v_pad[:, 1:-1] = self.v
        v_pad[:, 0] = self.v[:, 0]
        v_pad[:, -1] = self.v[:, -1]
        w_pad = np.empty((nx, ny, nz + 2), dtype=np.float32)
        w_pad[:, :, 1:-1] = self.w
        w_pad[:, :, 0] = -self.w[:, :, 0]
        w_pad[:, :, -1] = self.w[:, :, -1]

        divergence = (
            (u_pad[2:] - u_pad[:-2]) / (2.0 * self.dx[0])
            + (v_pad[:, 2:] - v_pad[:, :-2]) / (2.0 * self.dx[1])
            + (w_pad[:, :, 2:] - w_pad[:, :, :-2]) / (2.0 * self.dx[2])
        )
        del u_pad, v_pad, w_pad

        rhs = (divergence / dt).astype(np.float32)
        spectral = sfft.dct(rhs, type=4, axis=0, norm="ortho", overwrite_x=True)
        spectral = sfft.dct(spectral, type=2, axis=1, norm="ortho", overwrite_x=True)
        spectral = sfft.dct(spectral, type=2, axis=2, norm="ortho", overwrite_x=True)
        spectral /= self.poisson_denominator
        pressure = sfft.idct(spectral, type=2, axis=2, norm="ortho", overwrite_x=True)
        pressure = sfft.idct(pressure, type=2, axis=1, norm="ortho", overwrite_x=True)
        pressure = sfft.dct(pressure, type=4, axis=0, norm="ortho", overwrite_x=True)
        self.pressure = np.ascontiguousarray(pressure, dtype=np.float32)

        p_pad = np.empty((nx + 2, ny, nz), dtype=np.float32)
        p_pad[1:-1] = self.pressure
        p_pad[0] = self.pressure[0]
        p_pad[-1] = -self.pressure[-1]
        self.u -= dt * (p_pad[2:] - p_pad[:-2]) / (2.0 * self.dx[0])
        del p_pad
        p_pad = np.empty((nx, ny + 2, nz), dtype=np.float32)
        p_pad[:, 1:-1] = self.pressure
        p_pad[:, 0] = self.pressure[:, 0]
        p_pad[:, -1] = self.pressure[:, -1]
        self.v -= dt * (p_pad[:, 2:] - p_pad[:, :-2]) / (2.0 * self.dx[1])
        del p_pad
        p_pad = np.empty((nx, ny, nz + 2), dtype=np.float32)
        p_pad[:, :, 1:-1] = self.pressure
        p_pad[:, :, 0] = self.pressure[:, :, 0]
        p_pad[:, :, -1] = self.pressure[:, :, -1]
        self.w -= dt * (p_pad[:, :, 2:] - p_pad[:, :, :-2]) / (2.0 * self.dx[2])

    def _kernel(self, point, eps):
        """Separable normalised Gaussian support around a world point."""
        idx = (np.asarray(point, dtype=float) - self.low) / self.dx - 0.5
        base = np.floor(idx).astype(int)
        axis_index = []
        axis_weight = []
        for a in range(3):
            offs = base[a] + np.arange(-KERNEL_HALF + 1, KERNEL_HALF + 1)
            offs = offs[(offs >= 0) & (offs < self.shape[a])]
            if offs.size == 0:
                return None
            centres = self.low[a] + (offs + 0.5) * self.dx[a]
            axis_index.append(offs)
            axis_weight.append(np.exp(-(((centres - point[a]) / eps[a]) ** 2)))
        weights = (
            axis_weight[0][:, None, None]
            * axis_weight[1][None, :, None]
            * axis_weight[2][None, None, :]
        )
        total = float(weights.sum())
        if not np.isfinite(total) or total <= 1e-12:
            return None
        return np.ix_(*axis_index), (weights / total).astype(np.float32)

    def _rotate(self, vector, angle: float) -> np.ndarray:
        """Rodrigues rotation about the frozen axle direction."""
        a = self.axis
        vec = np.asarray(vector, dtype=float)
        return (
            vec * np.cos(angle)
            + np.cross(a, vec) * np.sin(angle)
            + a * float(a @ vec) * (1.0 - np.cos(angle))
        )

    def _blade_loads(self, theta: float, omega: float):
        """Actuator-line blade-element loads from the resolved local air velocity."""
        psi = theta + self.blade_offsets
        e_r = np.cos(psi)[:, None] * self.e1 + np.sin(psi)[:, None] * self.e2
        e_t = np.cross(np.broadcast_to(self.axis, e_r.shape), e_r)
        radii = self.elem_radius
        positions = self.hub + radii[None, :, None] * e_r[:, None, :]
        flat = positions.reshape(-1, 3)
        coords = ((flat - self.low) / self.dx - 0.5).T
        sampled = np.stack(
            [
                map_coordinates(f, coords, order=1, mode="nearest", prefilter=False)
                for f in (self.u, self.v, self.w)
            ],
            axis=-1,
        ).reshape(N_BLADES, N_ELEMENTS, 3)

        v_axial = sampled @ self.axis
        v_tangential = np.einsum("bec,bc->be", sampled, e_t)
        w_tangential = omega * radii[None, :] - v_tangential
        speed_sq = v_axial ** 2 + w_tangential ** 2
        phi = np.arctan2(v_axial, np.where(np.abs(w_tangential) < 1e-9, 1e-9, w_tangential))
        alpha = phi - self.elem_twist[None, :]
        lift, drag = _airfoil_coefficients(alpha)
        dyn = 0.5 * self.air_density * speed_sq * self.elem_chord[None, :] * self.elem_span
        tip = np.clip(
            1.0
            - np.exp(
                -N_BLADES
                * np.maximum(self.rotor_radius - radii[None, :], 0.0)
                / (0.06 + radii[None, :] * np.abs(np.sin(phi)))
            ),
            0.0,
            1.0,
        )
        f_axial = dyn * (lift * np.cos(phi) + drag * np.sin(phi)) * tip
        f_tangential = dyn * (lift * np.sin(phi) - drag * np.cos(phi)) * tip
        forces = (
            f_axial[:, :, None] * self.axis[None, None, :]
            + f_tangential[:, :, None] * e_t[:, None, :]
        )
        torque_axial = float(np.sum(radii[None, :] * f_tangential))
        return flat, forces.reshape(-1, 3), torque_axial

    def _deposit_forces(self, positions, forces, dt: float) -> None:
        """Equal and opposite reaction of the blades on the resolved air."""
        eps = 2.0 * self.dx
        scale = dt / (self.air_density * self.cell_volume)
        for point, force in zip(positions, forces):
            kernel = self._kernel(point, eps)
            if kernel is None:
                continue
            index, weights = kernel
            self.u[index] -= np.float32(scale * force[0]) * weights
            self.v[index] -= np.float32(scale * force[1]) * weights
            self.w[index] -= np.float32(scale * force[2]) * weights

    def _emit_smoke(self, dt: float, time: float, theta_start: float, theta_end: float) -> None:
        if time < self.emit_start or time > self.emit_end:
            return
        eps = np.maximum(np.full(3, self.source_radius), 0.9 * self.dx)
        amplitude = self.emit_rate * dt * 50.0 / N_EMIT_SUB
        for sub in range(N_EMIT_SUB):
            frac = (sub + 0.5) / N_EMIT_SUB
            angle = theta_start + frac * (theta_end - theta_start)
            for channel, local in enumerate(self.tip_local):
                point = self.hub + self._rotate(local, angle)
                kernel = self._kernel(point, eps)
                if kernel is None:
                    continue
                index, weights = kernel
                field = self.smoke[channel]
                field[index] = np.minimum(
                    field[index] + np.float32(amplitude) * weights * np.float32(weights.size),
                    np.float32(SMOKE_CEILING),
                )

    def _friction_torque(self, omega: float) -> float:
        """Frozen axle resisting torque: viscous plus regularized Coulomb."""
        return -(
            self.visc_friction * omega
            + self.coulomb_friction * np.tanh(omega / self.friction_eps)
        )

    def _step(self, dt: float, time: float) -> None:
        self._advect_velocity(dt)
        theta_start = self.theta
        sub = dt / N_SUBANGLE
        last = None
        for _ in range(N_SUBANGLE):
            positions, forces, tau_aero = self._blade_loads(self.theta, self.omega)
            self._deposit_forces(positions, forces, sub)
            tau_friction = self._friction_torque(self.omega)
            alpha = (tau_aero + tau_friction) / self.inertia_axial
            self.omega += sub * alpha
            self.theta += sub * self.omega
            self.angular_impulse += self.axis * (self.inertia_axial * sub * alpha)
            last = (positions, forces, tau_aero, tau_friction, alpha)
        if last is not None:
            self._store_terms(*last)

        self._apply_boundaries(time + dt)
        self._project(dt, time + dt)
        self._apply_boundaries(time + dt)

        self._advect_smoke(dt)
        self._emit_smoke(dt, time + dt, theta_start, self.theta)
        for field in self.smoke:
            field[field < 1e-4] = 0.0

        self.step_count += 1
        self.max_omega = max(self.max_omega, abs(self.omega))

    def _store_terms(self, positions, forces, tau_aero, tau_friction, alpha) -> None:
        """External force/couple decomposition of the rotor angular-momentum budget."""
        n = N_BLADES * N_ELEMENTS
        k = n + 4
        force_terms = np.zeros((1, k, 3))
        force_points = np.zeros((1, k, 3))
        couple_terms = np.zeros((1, k, 3))
        force_terms[0, :n] = np.asarray(forces, dtype=float)
        force_points[0, :n] = np.asarray(positions, dtype=float)

        weight = self.rotor_mass * GRAVITY
        force_terms[0, n] = weight
        force_points[0, n] = self.com
        # Revolute axle reaction holding the frozen centre of mass at rest.
        force_terms[0, n + 1] = -(force_terms[0, :n].sum(axis=0) + weight)
        force_points[0, n + 1] = self.hub
        couple_terms[0, n + 2] = self.axis * float(tau_friction)
        force_points[0, n + 2] = self.hub
        force_points[0, n + 3] = self.hub

        required = self.axis * (self.inertia_axial * float(alpha))
        applied = np.cross(force_points[0], force_terms[0]).sum(axis=0)
        applied = applied + couple_terms[0].sum(axis=0)
        couple_terms[0, n + 3] = required - applied

        self.budget_force = force_terms
        self.budget_position = force_points
        self.budget_couple = couple_terms
        self.interaction = np.asarray(force_terms[0, :n], dtype=float)
        self.tau_aero = float(tau_aero)
        self.tau_friction = float(tau_friction)
        self.alpha = float(alpha)

    def _downsample(self, field):
        nx, ny, nz = self.shape
        return field.reshape(nx // 2, 2, ny // 2, 2, nz // 2, 2).mean(axis=(1, 3, 5))

    def advance_to(self, time: float):
        target = float(time)
        if not np.isfinite(target) or target < self.time - 1e-12:
            raise ValueError("advance_to requires a finite non-decreasing time")
        remaining = target - self.time
        if remaining > 1e-12:
            count = max(1, int(np.ceil(remaining / MAX_SUBSTEP)))
            dt = remaining / count
            for _ in range(count):
                self._step(dt, self.time)
                self.time += dt
        self.time = target
        return self._make_frame(target)

    def _make_frame(self, time: float) -> StateFrame:
        angle = float(self.theta)
        half = 0.5 * angle
        orientation = np.array(
            [
                [
                    self.axis[0] * np.sin(half),
                    self.axis[1] * np.sin(half),
                    self.axis[2] * np.sin(half),
                    np.cos(half),
                ]
            ]
        )
        density = (
            self.air_density
            * (1.0 + self.pressure.astype(np.float64) / (SOUND_SPEED ** 2))
        )
        velocity_field = np.stack(
            (self._downsample(self.u), self._downsample(self.v), self._downsample(self.w)),
            axis=-1,
        )
        boundary_velocity = np.stack(
            (
                self.u[self.boundary_index],
                self.v[self.boundary_index],
                self.w[self.boundary_index],
            ),
            axis=-1,
        ).astype(float)
        inlet = np.asarray(self.scene.inlet_velocity(time), dtype=float)
        boundary_target = np.zeros_like(boundary_velocity)
        boundary_target[self.boundary_kind == 0] = inlet

        frame = StateFrame(
            time=float(time),
            position=self.com.reshape(1, 3).copy(),
            velocity=np.zeros((1, 3)),
            orientation=orientation,
            angular_velocity=(self.omega * self.axis).reshape(1, 3),
            mass=np.array([self.rotor_mass]),
            body_id=np.array([self.body_id], dtype=np.int64),
            attributes={
                "inertia_tensor": self.inertia_world.reshape(1, 3, 3).copy(),
                "mass_quantity": np.array([self.rotor_mass]),
                "rotor_angle": np.array([angle]),
                "rotor_angular_velocity": np.array([float(self.omega)]),
            },
            fields={
                "air_density": density.astype(np.float32),
                "velocity_field": velocity_field.astype(np.float32),
                "smoke_red": self.smoke[0].astype(np.float16),
                "smoke_green": self.smoke[1].astype(np.float16),
                "smoke_ochre": self.smoke[2].astype(np.float16),
                "boundary_normal": self.boundary_normal.copy(),
                "boundary_velocity": boundary_velocity,
                "boundary_target_velocity": boundary_target,
                "budget_domain_weights": np.ones((1, 1)),
                "budget_external_force": self.budget_force.copy(),
                "budget_force_position": self.budget_position.copy(),
                "budget_external_couple": self.budget_couple.copy(),
                "budget_cumulative_external_angular_impulse": self.angular_impulse.reshape(1, 3).copy(),
                "budget_cumulative_inflow_angular_momentum": np.zeros((1, 3)),
                "budget_cumulative_outflow_angular_momentum": np.zeros((1, 3)),
                "cumulative_mass_source": np.zeros(1),
                "interaction_force": self.interaction.copy(),
                "gravity_acceleration": GRAVITY.reshape(1, 3).copy(),
                "grid_origin": self.low.copy(),
                "grid_spacing": self.dx.copy(),
                "rotor_local_tip_positions": self.tip_local.copy(),
            },
            scalars={
                "reference_velocity": self.inlet_speed,
                "reference_angular_momentum": self.inertia_axial
                * self.inlet_speed
                / self.rotor_radius,
                "air_density": self.air_density,
                "inlet_speed": self.inlet_speed,
                "axle_viscous_friction": self.visc_friction,
                "axle_coulomb_friction": self.coulomb_friction,
                "rotor_radius": self.rotor_radius,
                "rotor_inertia_axial": self.inertia_axial,
                "rotor_angular_speed": float(self.omega),
                "tip_speed_ratio": abs(self.omega) * self.rotor_radius / max(self.inlet_speed, 1e-9),
                "aerodynamic_torque": self.tau_aero,
                "axle_friction_torque": self.tau_friction,
                "angular_acceleration": self.alpha,
            },
        )
        frame.validate()
        return frame

    def diagnostics(self) -> dict[str, object]:
        return {
            "steps": int(self.step_count),
            "final_time": float(self.time),
            "final_angular_speed": float(self.omega),
            "max_angular_speed": float(self.max_omega),
            "final_rotor_angle": float(self.theta),
            "rotor_inertia_axial": float(self.inertia_axial),
            "final_aerodynamic_torque": float(self.tau_aero),
            "final_friction_torque": float(self.tau_friction),
            "final_tip_speed_ratio": float(
                abs(self.omega) * self.rotor_radius / max(self.inlet_speed, 1e-9)
            ),
        }

