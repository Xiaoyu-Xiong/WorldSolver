    def diagnostics(self) -> dict[str, object]:
        return {
            "solver": "elastic_bag_sph_coupled",
            "substeps_per_frame": self._substeps,
            "dt_physics": self._dt,
            "n_bag": self._n_bag,
            "n_water": self._n_water,
            "total_mass": float(self._m.sum()),
        }
