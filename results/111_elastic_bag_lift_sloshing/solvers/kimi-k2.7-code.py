"""Two-way coupled elastic-bag / SPH-water solver.

The bag is modelled as a triangle-mesh cloth with Hookean edge springs and
customary damping.  Water is modelled with weakly-compressible SPH
(Poly6/Tait).  Coupling is a strong penalty contact between the water
particles and a dense point-cloud sampled from the bag surface (vertices,
face centroids and edge midpoints).  The only scripted motion is the rim
lift; all other solid and fluid motion is generated by the numerical time
stepping.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.spatial import cKDTree

from worldsolver.contracts import StateFrame


class BenchmarkSolver:
    def initialize(self, scene, seed: int) -> None:
        self._seed = int(seed)
        self._scene = scene

        # ---- frozen initial state ------------------------------------------------
        frame = scene.initial_state()
        frame.validate()
        self._x = np.asarray(frame.position, dtype=float).copy()
        self._v = np.asarray(frame.velocity, dtype=float).copy()
        self._m = np.asarray(frame.mass, dtype=float).copy()
        self._body_id = np.asarray(frame.body_id, dtype=np.int32).copy()
        self._time = 0.0

        # ---- masks ----------------------------------------------------------------
        self._bag_mask = self._body_id == 0
        self._water_mask = self._body_id == 1
        self._bag_idx = np.nonzero(self._bag_mask)[0]
        self._water_idx = np.nonzero(self._water_mask)[0]
        self._n_bag = len(self._bag_idx)
        self._n_water = len(self._water_idx)

        # ---- constants ------------------------------------------------------------
        cfg = scene.config if hasattr(scene, "config") else {}
        self._gravity = np.asarray(cfg.get("gravity", [0.0, 0.0, -9.81]), dtype=float)

        bc = cfg.get("boundary_conditions", {})
        tank = bc.get("tank", {})
        self._tank_min = np.asarray(tank.get("interior_min", [-1.8, -1.5, 0.0]), dtype=float)
        self._tank_max = np.asarray(tank.get("interior_max", [1.8, 1.5, 3.2]), dtype=float)
        self._open_top = tank.get("open_top", True)

        # ---- rim lift parameters ---------------------------------------------------
        rim_cfg = bc.get("rim_lift", {})
        self._rim_start = float(rim_cfg.get("start_time", 0.2))
        self._rim_dur = float(rim_cfg.get("rise_duration", 0.75))
        self._rim_start_center = np.asarray(rim_cfg.get("start_center", [0.0, 0.0, 1.1]), dtype=float)
        self._rim_end_center = np.asarray(rim_cfg.get("end_center", [0.0, 0.0, 2.58]), dtype=float)

        # ---- bag topology ---------------------------------------------------------
        # Access the loaded asset via the scene (private attributes are stable).
        faces = np.asarray(scene._bag_faces, dtype=np.int32)
        self._rim_local = np.asarray(scene._rim_indices, dtype=np.int32)
        # Local bag ordering is the same as the bag block in the state frame.
        self._faces = faces  # local indices, shape (F,3)

        # Unique edges for the spring network.
        e1 = np.stack((faces[:, 0], faces[:, 1]), axis=1)
        e2 = np.stack((faces[:, 1], faces[:, 2]), axis=1)
        e3 = np.stack((faces[:, 2], faces[:, 0]), axis=1)
        edges = np.vstack((e1, e2, e3))
        edges = np.sort(edges, axis=1)
        self._edges = np.unique(edges, axis=0)  # (E,2)

        # Reference configuration for the bag.
        self._x0_bag = self._x[self._bag_idx].copy()
        self._edge_rest = np.linalg.norm(
            self._x0_bag[self._edges[:, 1]] - self._x0_bag[self._edges[:, 0]], axis=1
        )

        # Surface sample tables for bag-water contact.
        self._build_surface_tables()

        # ---- simulation parameters ------------------------------------------------
        self._substeps = 20          # 0.02 / 20 = 1e-3 s physics dt
        self._dt = 0.02 / self._substeps
        self._h_sph = 0.15
        self._rho0 = 1000.0
        self._c0 = 60.0
        self._gamma = 7.0
        self._B = (self._c0 * self._c0) * self._rho0 / self._gamma
        self._alpha_visc = 0.08

        # Bag stiffness/damping chosen for a light but stable cloth.
        self._k_edge = 8.0e3
        self._c_edge = 2.0
        self._k_contact = 1.5e4
        self._c_contact = 0.5
        self._contact_cutoff = 0.08
        self._wall_margin = 0.02
        self._k_wall = 5.0e4
        self._c_wall = 0.8

        # ---- budget / bookkeeping ------------------------------------------------
        self._cum_external_impulse = np.zeros((2, 3), dtype=float)
        self._cum_inflow_momentum = np.zeros((2, 3), dtype=float)
        self._cum_outflow_momentum = np.zeros((2, 3), dtype=float)
        self._cum_mass_source = np.zeros(2, dtype=float)

        total_mass = float(self._m.sum())
        self._ref_velocity = 3.5
        self._ref_momentum = total_mass * self._ref_velocity

        # Static boundary samples for the tank walls.
        self._boundary_normal, self._boundary_target, self._boundary_velocity = self._tank_boundary_samples()

    # -------------------------------------------------------------------------
    def _build_surface_tables(self) -> None:
        """Build index/weight tables for vertex, face and edge surface samples."""
        B = self._n_bag
        F = self._faces.shape[0]
        E = self._edges.shape[0]

        total = B + F + E
        self._samp_v0 = np.full(total, -1, dtype=np.int32)
        self._samp_v1 = np.full(total, -1, dtype=np.int32)
        self._samp_v2 = np.full(total, -1, dtype=np.int32)
        self._samp_w0 = np.zeros(total, dtype=float)
        self._samp_w1 = np.zeros(total, dtype=float)
        self._samp_w2 = np.zeros(total, dtype=float)

        # vertex samples
        self._samp_v0[:B] = np.arange(B, dtype=np.int32)
        self._samp_w0[:B] = 1.0

        # face samples
        fstart = B
        self._samp_v0[fstart:fstart + F] = self._faces[:, 0]
        self._samp_v1[fstart:fstart + F] = self._faces[:, 1]
        self._samp_v2[fstart:fstart + F] = self._faces[:, 2]
        self._samp_w0[fstart:fstart + F] = 1.0 / 3.0
        self._samp_w1[fstart:fstart + F] = 1.0 / 3.0
        self._samp_w2[fstart:fstart + F] = 1.0 / 3.0

        # edge midpoint samples
        estart = B + F
        self._samp_v0[estart:estart + E] = self._edges[:, 0]
        self._samp_v1[estart:estart + E] = self._edges[:, 1]
        self._samp_w0[estart:estart + E] = 0.5
        self._samp_w1[estart:estart + E] = 0.5

    def _surface_samples(self, x_bag: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Return positions and normals of the bag surface samples."""
        B = self._n_bag
        F = self._faces.shape[0]
        E = self._edges.shape[0]
        pos = np.empty((B + F + E, 3), dtype=float)
        norm = np.zeros_like(pos)

        # vertex positions / normals
        pos[:B] = x_bag
        face_norm = np.cross(
            x_bag[self._faces[:, 1]] - x_bag[self._faces[:, 0]],
            x_bag[self._faces[:, 2]] - x_bag[self._faces[:, 0]],
        )
        fn_len = np.linalg.norm(face_norm, axis=1, keepdims=True)
        fn_len[fn_len == 0] = 1.0
        face_norm = face_norm / fn_len
        np.add.at(norm, self._faces[:, 0], face_norm)
        np.add.at(norm, self._faces[:, 1], face_norm)
        np.add.at(norm, self._faces[:, 2], face_norm)
        nlen = np.linalg.norm(norm[:B], axis=1, keepdims=True)
        mask = nlen[:, 0] > 0
        norm[:B][mask] /= nlen[mask]

        # face centroids and normals
        fstart = B
        pos[fstart:fstart + F] = (
            x_bag[self._faces[:, 0]]
            + x_bag[self._faces[:, 1]]
            + x_bag[self._faces[:, 2]]
        ) / 3.0
        norm[fstart:fstart + F] = face_norm

        # edge midpoints and normals (average of end-vertex normals)
        estart = B + F
        i0 = self._edges[:, 0]
        i1 = self._edges[:, 1]
        pos[estart:estart + E] = (x_bag[i0] + x_bag[i1]) * 0.5
        en = (norm[i0] + norm[i1]) / 2.0
        elen = np.linalg.norm(en, axis=1, keepdims=True)
        elen[elen == 0] = 1.0
        en = en / elen
        norm[estart:estart + E] = en

        return pos, norm

    # -------------------------------------------------------------------------
    def _rim_target(self, t: float) -> tuple[np.ndarray, np.ndarray]:
        """Return target displacement and velocity for the rim lift."""
        if t <= self._rim_start:
            disp = np.zeros(3, dtype=float)
            vel = np.zeros(3, dtype=float)
        elif t >= self._rim_start + self._rim_dur:
            disp = self._rim_end_center - self._rim_start_center
            vel = np.zeros(3, dtype=float)
        else:
            s = (t - self._rim_start) / self._rim_dur
            disp = (self._rim_end_center - self._rim_start_center) * s
            vel = (self._rim_end_center - self._rim_start_center) / self._rim_dur
        return disp, vel

    # -------------------------------------------------------------------------
    def _sph_forces(self, x: np.ndarray, v: np.ndarray, m: np.ndarray) -> np.ndarray:
        n = x.shape[0]
        f = np.zeros_like(x)
        if n == 0:
            return f

        tree = cKDTree(x)
        pairs = tree.sparse_distance_matrix(tree, 2.0 * self._h_sph, output_type="coo")
        i = pairs.row
        j = pairs.col
        d = pairs.data
        # Keep only pairs inside the Poly6 support (exclude self)
        valid = (i != j) & (d < self._h_sph) & (d > 0.0)
        i = i[valid]
        j = j[valid]
        d = d[valid]
        if i.size == 0:
            return f

        rvec = x[i] - x[j]
        h2 = self._h_sph * self._h_sph
        d2 = d * d
        C = 315.0 / (64.0 * np.pi * self._h_sph ** 9)
        W = C * (h2 - d2) ** 3
        # gradW = -6 C (h^2 - r^2)^2 r_vec
        tmp = (h2 - d2) ** 2
        gradW = -6.0 * C * tmp[:, None] * rvec

        # Density
        density = np.zeros(n, dtype=float)
        np.add.at(density, i, m[j] * W)

        # Pressure (Tait, clamped to non-negative)
        p = self._B * ((density / self._rho0) ** self._gamma - 1.0)
        p = np.maximum(p, 0.0)
        prho2 = p / (density ** 2)
        prho2[density <= 0.0] = 0.0

        # Pressure force: f_i += -m_i m_j (p_i/rho_i^2 + p_j/rho_j^2) grad_i W
        term = prho2[i] + prho2[j]
        f_pair = -(m[i] * m[j])[:, None] * term[:, None] * gradW
        np.add.at(f, i, f_pair)
        np.add.at(f, j, -f_pair)

        # Artificial viscosity (Monaghan)
        vdiff = v[i] - v[j]
        vdotr = np.sum(vdiff * rvec, axis=1)
        active = vdotr < 0.0
        if np.any(active):
            ia = i[active]
            ja = j[active]
            rva = rvec[active]
            dva = d[active]
            vdot = vdotr[active]
            mu = self._h_sph * vdot / (dva ** 2 + 0.01 * self._h_sph ** 2)
            pi = (-self._alpha_visc * self._c0 * mu) / (density[ia] + density[ja])
            fvis = -(m[ia] * m[ja])[:, None] * pi[:, None] * gradW[active]
            np.add.at(f, ia, fvis)
            np.add.at(f, ja, -fvis)

        return f

    def _bag_elastic_forces(self, x: np.ndarray, v: np.ndarray) -> np.ndarray:
        n = x.shape[0]
        f = np.zeros_like(x)
        if n == 0:
            return f
        i0 = self._edges[:, 0]
        i1 = self._edges[:, 1]
        x0 = x[i0]
        x1 = x[i1]
        dx = x1 - x0
        L = np.linalg.norm(dx, axis=1)
        L[L == 0] = 1.0
        e = dx / L[:, None]
        # Spring force
        delta = L - self._edge_rest
        f_mag = self._k_edge * delta
        # Damping along the spring
        v0 = v[i0]
        v1 = v[i1]
        v_rel = np.sum((v1 - v0) * e, axis=1)
        f_damp = self._c_edge * v_rel
        f_total = (f_mag + f_damp)[:, None] * e
        np.add.at(f, i0, f_total)
        np.add.at(f, i1, -f_total)
        return f

    def _bag_water_contact(
        self,
        x_all: np.ndarray,
        v_all: np.ndarray,
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Return (force on water, force on bag, interaction_force)."""
        x_bag = x_all[self._bag_idx]
        x_w = x_all[self._water_idx]
        v_b = v_all[self._bag_idx]
        v_w = v_all[self._water_idx]

        f_w = np.zeros_like(x_w)
        f_b = np.zeros_like(x_b)
        if self._n_water == 0 or self._n_bag == 0:
            return f_w, f_b, np.zeros((1, 3), dtype=float)

        pos, norm = self._surface_samples(x_bag)
        tree = cKDTree(pos)
        dist, idx = tree.query(x_w, k=1, distance_upper_bound=self._contact_cutoff)
        active = np.isfinite(dist) & (dist < self._contact_cutoff) & (idx >= 0)
        if not np.any(active):
            return f_w, f_b, np.zeros((1, 3), dtype=float)

        idx = idx[active]
        pw = x_w[active]
        vw = v_w[active]
        base = pos[idx]
        n = norm[idx]
        # signed distance: positive on the side of the normal, negative opposite
        d_s = np.sum((pw - base) * n, axis=1)
        abs_d = np.abs(d_s)
        factor = np.maximum(0.0, self._contact_cutoff - abs_d)
        # Double-sided penalty: always push the water back toward the surface
        f_dir = -(np.sign(d_s)[:, None] * n) * (self._k_contact * factor[:, None])

        # Damping relative to surface velocity
        v_surf = (
            self._samp_w0[idx][:, None] * v_b[self._samp_v0[idx]]
            + self._samp_w1[idx][:, None] * v_b[self._samp_v1[idx]]
            + self._samp_w2[idx][:, None] * v_b[self._samp_v2[idx]]
        )
        vrel = vw - v_surf
        v_n = np.sum(vrel * n, axis=1)
        f_damp = -self._c_contact * v_n[:, None] * n

        f_contact = f_dir + f_damp
        f_w[active] = f_contact

        # Reaction distributed to bag vertices with the stored weights
        flat_v0 = self._samp_v0[idx]
        flat_v1 = self._samp_v1[idx]
        flat_v2 = self._samp_v2[idx]
        # vertex 0
        valid = flat_v0 >= 0
        np.add.at(f_b, flat_v0[valid], -f_contact[valid] * self._samp_w0[idx][valid][:, None])
        # vertex 1
        valid = flat_v1 >= 0
        np.add.at(f_b, flat_v1[valid], -f_contact[valid] * self._samp_w1[idx][valid][:, None])
        # vertex 2
        valid = flat_v2 >= 0
        np.add.at(f_b, flat_v2[valid], -f_contact[valid] * self._samp_w2[idx][valid][:, None])

        interaction = f_b.sum(axis=0, keepdims=True)
        return f_w, f_b, interaction

    def _wall_forces(self, x: np.ndarray, v: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Return (per-particle force, total wall force per domain)."""
        f = np.zeros_like(x)
        # x min / max
        for axis in (0, 1):
            lo = self._tank_min[axis]
            hi = self._tank_max[axis]
            pen_lo = self._wall_margin + lo - x[:, axis]
            pen_hi = x[:, axis] - (hi - self._wall_margin)
            active_lo = pen_lo > 0.0
            active_hi = pen_hi > 0.0
            f[active_lo, axis] += self._k_wall * pen_lo[active_lo] - self._c_wall * v[active_lo, axis]
            f[active_hi, axis] += -self._k_wall * pen_hi[active_hi] - self._c_wall * v[active_hi, axis]
        # floor
        pen_z = self._wall_margin - x[:, 2]
        active_z = pen_z > 0.0
        f[active_z, 2] += self._k_wall * pen_z[active_z] - self._c_wall * v[active_z, 2]
        # no top wall (open tank)

        total = f.sum(axis=0)
        return f, total

    # -------------------------------------------------------------------------
    def _tank_boundary_samples(self) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Produce static wall sample points/normals/velocities for the tank."""
        samples = []
        normals = []
        # floor z=0, outward normal -z
        xs = np.linspace(self._tank_min[0] + 0.1, self._tank_max[0] - 0.1, 3)
        ys = np.linspace(self._tank_min[1] + 0.1, self._tank_max[1] - 0.1, 2)
        xv, yv = np.meshgrid(xs, ys)
        for xx, yy in zip(xv.ravel(), yv.ravel()):
            samples.append([xx, yy, 0.0])
            normals.append([0.0, 0.0, -1.0])
        # back wall y = tank_max[1]
        for xx in np.linspace(self._tank_min[0] + 0.2, self._tank_max[0] - 0.2, 3):
            for zz in np.linspace(0.1, self._tank_max[2] - 0.2, 2):
                samples.append([xx, self._tank_max[1], zz])
                normals.append([0.0, 1.0, 0.0])
        # left wall x = tank_min[0]
        for yy in np.linspace(self._tank_min[1] + 0.2, self._tank_max[1] - 0.2, 3):
            for zz in np.linspace(0.1, self._tank_max[2] - 0.2, 2):
                samples.append([self._tank_min[0], yy, zz])
                normals.append([-1.0, 0.0, 0.0])
        # right wall x = tank_max[0]
        for yy in np.linspace(self._tank_min[1] + 0.2, self._tank_max[1] - 0.2, 3):
            for zz in np.linspace(0.1, self._tank_max[2] - 0.2, 2):
                samples.append([self._tank_max[0], yy, zz])
                normals.append([1.0, 0.0, 0.0])
        nvec = np.asarray(normals, dtype=float)
        nlen = np.linalg.norm(nvec, axis=1, keepdims=True)
        nlen[nlen == 0] = 1.0
        nvec = nvec / nlen
        return nvec, np.zeros_like(nvec), np.zeros_like(nvec)

    # -------------------------------------------------------------------------
    def _compute_frame(self, time: float) -> StateFrame:
        # Domain masks
        bag = self._body_id == 0
        water = self._body_id == 1

        # External gravity totals per domain
        grav_bag = (self._m[bag, None] * self._gravity[None, :]).sum(axis=0)
        grav_water = (self._m[water, None] * self._gravity[None, :]).sum(axis=0)

        # wall contact totals updated during sub-stepping below
        last_wall = getattr(self, "_last_wall_force", np.zeros((2, 3), dtype=float))

        budget_external_force = np.zeros((2, 2, 3), dtype=float)
        budget_external_force[0, 0] = grav_bag
        budget_external_force[1, 0] = grav_water
        budget_external_force[:, 1] = last_wall

        # Interaction force at this moment (bag-water contact)
        _, _, interaction = self._bag_water_contact(self._x, self._v)

        # Domain weights
        weights = np.zeros((2, len(self._x)), dtype=float)
        weights[0, bag] = 1.0
        weights[1, water] = 1.0

        return StateFrame(
            time=time,
            position=self._x.copy(),
            velocity=self._v.copy(),
            mass=self._m.copy(),
            body_id=self._body_id.copy(),
            attributes={
                "mass_quantity": self._m.copy(),
            },
            fields={
                "boundary_normal": self._boundary_normal.copy(),
                "boundary_target_velocity": self._boundary_target.copy(),
                "boundary_velocity": self._boundary_velocity.copy(),
                "budget_cumulative_external_impulse": self._cum_external_impulse.copy(),
                "budget_cumulative_inflow_momentum": self._cum_inflow_momentum.copy(),
                "budget_cumulative_outflow_momentum": self._cum_outflow_momentum.copy(),
                "budget_domain_weights": weights,
                "budget_external_force": budget_external_force,
                "cumulative_mass_source": self._cum_mass_source.copy(),
                "interaction_force": interaction.copy(),
            },
            scalars={
                "reference_momentum": float(self._ref_momentum),
                "reference_velocity": float(self._ref_velocity),
            },
        )

    # -------------------------------------------------------------------------
    def advance_to(self, time: float) -> StateFrame:
        if time < self._time:
            raise ValueError("advance_to time must be non-decreasing")
        if time == self._time:
            return self._compute_frame(time)

        # Step forward in substeps until the requested time.
        n_steps = int(round((time - self._time) / self._dt))
        for _ in range(n_steps):
            self._substep(self._time + self._dt)
            self._time += self._dt

        # If there is a tiny floating remainder due to rounding, take one final substep.
        while self._time < time - 1e-12:
            self._substep(time)
            self._time = time
        return self._compute_frame(time)

    def _substep(self, t_next: float) -> None:
        dt = self._dt
        x = self._x
        v = self._v
        m = self._m

        f = np.zeros_like(x)

        # Gravity
        f += m[:, None] * self._gravity[None, :]

        # SPH water-water
        if self._n_water > 0:
            f_w = self._sph_forces(x[self._water_idx], v[self._water_idx], m[self._water_idx])
            f[self._water_idx] += f_w

        # Bag elastic forces
        if self._n_bag > 0:
            f_b = self._bag_elastic_forces(x[self._bag_idx], v[self._bag_idx])
            f[self._bag_idx] += f_b

        # Bag-water contact
        if self._n_water > 0 and self._n_bag > 0:
            fc_w, fc_b, _ = self._bag_water_contact(x, v)
            f[self._water_idx] += fc_w
            f[self._bag_idx] += fc_b

        # Wall/contact with tank
        f_wall, wall_total = self._wall_forces(x, v)
        f += f_wall
        self._last_wall_force = np.zeros((2, 3), dtype=float)
        self._last_wall_force[0] = f_wall[self._bag_mask].sum(axis=0)
        self._last_wall_force[1] = f_wall[self._water_mask].sum(axis=0)

        # Update velocities and positions (symplectic Euler)
        a = f / m[:, None]
        v_new = v + dt * a
        x_new = x + dt * v_new

        # Enforce rim kinematics on the bag rim vertices.
        disp, vel = self._rim_target(t_next)
        rim_global = self._bag_idx[self._rim_local]
        x_new[rim_global] = self._x0_bag[self._rim_local] + disp
        v_new[rim_global] = vel

        # Enforce tank walls by hard clamping (keeps particles inside).
        for axis in (0, 1):
            x_new[:, axis] = np.clip(x_new[:, axis], self._tank_min[axis], self._tank_max[axis])
        x_new[:, 2] = np.maximum(x_new[:, 2], self._tank_min[2])
        if not self._open_top:
            x_new[:, 2] = np.minimum(x_new[:, 2], self._tank_max[2])

        self._x = x_new
        self._v = v_new

        # Update budget accumulators.
        # External impulse from gravity + walls.
        external_per_domain = np.zeros((2, 3), dtype=float)
        external_per_domain[0] = (m[self._bag_mask, None] * self._gravity[None, :]).sum(axis=0)
        external_per_domain[1] = (m[self._water_mask, None] * self._gravity[None, :]).sum(axis=0)
        external_per_domain[0] += self._last_wall_force[0]
        external_per_domain[1] += self._last_wall_force[1]
        self._cum_external_impulse += external_per_domain * dt

