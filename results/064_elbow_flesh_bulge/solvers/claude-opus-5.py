"""Explicit stable neo-Hookean FEM solver for elbow-flexion flesh bulging.

Physics
-------
The arm flesh is a three-dimensional elastic solid discretised with linear
tetrahedra.  The frozen watertight surface asset supplies the skin nodes (they
are exported unchanged, in the original vertex order, so the frozen topology
stays valid).  Interior nodes are generated by shrinking every cross-section
ring toward the arm axis so that the innermost node layer coincides with the
driven bone capsules.

Constitutive model (Smith, Goldade, Kim, Barbic 2018, "Stable Neo-Hookean
Flesh Simulation"):

    Psi(F) = mu/2 (Ic - 3) + lam/2 (J - alpha)^2 - mu/2 log(Ic + 1)
    alpha  = 1 + mu/lam - mu/(4 lam)
    P(F)   = mu (1 - 1/(Ic + 1)) F + lam (J - alpha) dJ/dF

with dJ/dF the cofactor matrix of F.  The model is inversion safe and rest
stable, and the large lam/mu ratio makes the tissue nearly incompressible,
which is what forces the squeezed elbow flesh outward instead of letting it
vanish.  A Kelvin-Voigt viscous stress beta * dF/dt supplies material damping.

Boundary conditions: nodes inside the humerus capsule are held fixed, nodes
inside the forearm capsule follow the prescribed smoothstep hinge rotation, and
the two terminal cross-sections are clamped to their bone.  Penalty contact
between skin nodes and against both bone capsules prevents interpenetration at
the closing crease.  Time integration is symplectic (semi-implicit) Euler with
a fixed sub-step well below the elastic CFL limit.
"""
from __future__ import annotations

import numpy as np

from worldsolver.contracts import StateFrame

GRAVITY = np.array([0.0, 0.0, -9.81], dtype=float)
TOTAL_FLESH_MASS = 3.05

_DEFAULT_BONES = {
    "humerus_bone": {"radius": 0.05, "height": 0.62, "translation": (-0.36, 0.0, 1.05),
                     "rotation_xyzw": (0.0, 0.70710678, 0.0, 0.70710678)},
    "forearm_bone": {"radius": 0.04, "height": 0.66, "translation": (0.38, 0.0, 1.05),
                     "rotation_xyzw": (0.0, 0.70710678, 0.0, 0.70710678)},
}


def _quat_matrix(q) -> np.ndarray:
    x, y, z, w = (float(v) for v in q)
    n = np.sqrt(x * x + y * y + z * z + w * w)
    if n == 0.0:
        return np.eye(3)
    x, y, z, w = x / n, y / n, z / n, w / n
    return np.array([
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ], dtype=float)


def _rotation(axis: np.ndarray, angle: float) -> np.ndarray:
    k = np.array([[0.0, -axis[2], axis[1]],
                  [axis[2], 0.0, -axis[0]],
                  [-axis[1], axis[0], 0.0]], dtype=float)
    return np.eye(3) + np.sin(angle) * k + (1.0 - np.cos(angle)) * (k @ k)


def _segment_distance(points: np.ndarray, a: np.ndarray, b: np.ndarray):
    """Distance from points to the segment ab plus the outward offset vectors."""
    d = b - a
    l2 = float(d @ d)
    w = points - a
    if l2 > 0.0:
        s = np.clip((w @ d) / l2, 0.0, 1.0)
    else:
        s = np.zeros(len(points))
    delta = points - (a + s[:, None] * d)
    dist = np.sqrt(np.einsum("ij,ij->i", delta, delta))
    return dist, delta


def _hinge_state(t: float, t0: float, t1: float, a0: float, a1: float):
    """Smoothstep hinge angle, angular rate and angular acceleration."""
    span = max(t1 - t0, 1e-12)
    s = (t - t0) / span
    if s <= 0.0:
        return a0, 0.0, 0.0
    if s >= 1.0:
        return a1, 0.0, 0.0
    delta = a1 - a0
    angle = a0 + delta * (s * s * (3.0 - 2.0 * s))
    rate = delta * (6.0 * s - 6.0 * s * s) / span
    accel = delta * (6.0 - 12.0 * s) / (span * span)
    return angle, rate, accel

class BenchmarkSolver:
    """Volumetric neo-Hookean flesh driven by kinematic bones."""

    def initialize(self, scene, seed: int) -> None:
        config = dict(getattr(scene, "config", {}) or {})
        self._rng = np.random.default_rng(int(seed))
        bc = dict(config.get("boundary_conditions", {}) or {})
        hinge = dict(bc.get("forearm_bone", {}) or {})
        self.hinge_center = np.asarray(
            hinge.get("hinge_center", [0.0, 0.0, 1.05]), dtype=float)
        axis = np.asarray(hinge.get("hinge_axis", [0.0, 1.0, 0.0]), dtype=float)
        norm = np.linalg.norm(axis)
        self.hinge_axis = axis / norm if norm > 0 else np.array([0.0, 1.0, 0.0])
        self.t_start = float(hinge.get("start_time", 0.4))
        self.t_end = float(hinge.get("end_time", 2.4))
        self.angle0 = np.deg2rad(float(hinge.get("start_angle_degrees", 0.0)))
        self.angle1 = np.deg2rad(float(hinge.get("end_angle_degrees", -110.0)))

        ic = dict(config.get("initial_conditions", {}) or {})
        self.density = float(ic.get("flesh_density_kg_m3", 1050.0))
        # Soft-tissue moduli: nearly incompressible so that compressed flesh
        # must bulge outward rather than lose volume.
        self.mu = 2.0e4
        self.lam = 2.0e5
        self.alpha = 1.0 + self.mu / self.lam - self.mu / (4.0 * self.lam)
        self.beta = 60.0            # Kelvin-Voigt viscosity [Pa s]
        self.k_self = 3.0e4         # skin-skin penalty stiffness [N/m]
        self.k_bone = 6.0e4         # bone penalty stiffness [N/m]
        self.c_contact = 6.0        # contact normal damping [N s/m]
        self.d_self = 0.045         # skin-skin contact thickness [m]
        self.dt_max = 6.0e-5

        self._read_bones(config)
        rest = np.asarray(scene.initial_state().position, dtype=float)
        self.skin_rest = rest.copy()
        self.n_skin = len(rest)
        self._build_mesh(rest)
        self._build_attachments()
        self._build_contact_sets()

        self.position = self.rest.copy()
        self.velocity = np.zeros_like(self.rest)
        self.time = 0.0
        self._broad_pairs = self._self_pairs
        self._broad_step = 0
        self._max_j = 1.0
        self._min_j = 1.0

    # ------------------------------------------------------------------ setup
    def _read_bones(self, config: dict) -> None:
        specs = {}
        geometry = config.get("scene_geometry") or {}
        for item in geometry.get("objects", []) or []:
            oid = str(item.get("id", ""))
            if oid in _DEFAULT_BONES:
                geom = item.get("geometry", {}) or {}
                tr = item.get("transform", {}) or {}
                specs[oid] = {
                    "radius": float(geom.get("radius", _DEFAULT_BONES[oid]["radius"])),
                    "height": float(geom.get("height", _DEFAULT_BONES[oid]["height"])),
                    "translation": np.asarray(
                        tr.get("translation", _DEFAULT_BONES[oid]["translation"]), float),
                    "rotation_xyzw": np.asarray(
                        tr.get("rotation_xyzw", _DEFAULT_BONES[oid]["rotation_xyzw"]), float),
                }
        for oid, default in _DEFAULT_BONES.items():
            if oid not in specs:
                specs[oid] = {
                    "radius": default["radius"],
                    "height": default["height"],
                    "translation": np.asarray(default["translation"], float),
                    "rotation_xyzw": np.asarray(default["rotation_xyzw"], float),
                }
        self.bones = {}
        for oid, spec in specs.items():
            axis = _quat_matrix(spec["rotation_xyzw"]) @ np.array([0.0, 0.0, 1.0])
            half = 0.5 * spec["height"]
            self.bones[oid] = {
                "radius": spec["radius"],
                "a": spec["translation"] - half * axis,
                "b": spec["translation"] + half * axis,
            }

    def _build_mesh(self, rest: np.ndarray) -> None:
        """Group the frozen surface into cross-section rings, add interior layers."""
        x = rest[:, 0]
        levels = np.unique(np.round(x, 6))
        rings = []
        poles = []
        for lev in levels:
            idx = np.where(np.abs(x - lev) < 1e-6)[0]
            centre = np.array([lev, self.hinge_center[1], self.hinge_center[2]])
            radial = rest[idx] - centre
            r = np.hypot(radial[:, 1], radial[:, 2])
            on_axis = idx[r < 1e-9]
            ring = idx[r >= 1e-9]
            if len(ring) >= 3:
                ang = np.arctan2(rest[ring, 2] - centre[2], rest[ring, 1] - centre[1])
                ring = ring[np.argsort(ang)]
                rings.append((float(lev), ring))
            poles.extend(int(i) for i in on_axis)
        sizes = {len(r) for _, r in rings}
        m = min(sizes)
        rings = [(lev, r[:m]) for lev, r in rings]
        self.n_ring = m
        self.ring_levels = np.array([lev for lev, _ in rings])
        self.ring_index = [r for _, r in rings]
        n_rings = len(rings)

        nodes = [rest]
        # radial scales from bone surface outward; 1.0 is the frozen skin
        scales = [0.32, 0.66]
        layer_idx = []       # layer_idx[k][i] -> node ids of interior layer k, ring i
        axis_idx = []        # one axis node per ring
        count = len(rest)
        pole_map = {}
        for p in poles:
            pole_map[float(round(rest[p, 0], 6))] = int(p)
        for _k, sc in enumerate(scales):
            layer = []
            for i, (lev, ring) in enumerate(rings):
                centre = np.array([lev, self.hinge_center[1], self.hinge_center[2]])
                pts = centre + sc * (rest[ring] - centre)
                nodes.append(pts)
                layer.append(np.arange(count, count + len(ring)))
                count += len(ring)
            layer_idx.append(layer)
        for i, (lev, _ring) in enumerate(rings):
            key = float(round(lev, 6))
            if key in pole_map:
                axis_idx.append(pole_map[key])
            else:
                centre = np.array([[lev, self.hinge_center[1], self.hinge_center[2]]])
                nodes.append(centre)
                axis_idx.append(count)
                count += 1
        self.rest = np.vstack(nodes)
        self.n_nodes = len(self.rest)
        axis_idx = np.asarray(axis_idx, dtype=int)

        # ---- tetrahedra ---------------------------------------------------
        tets = []
        skin_layer = [np.asarray(r, dtype=int) for _, r in rings]
        shells = layer_idx + [skin_layer]     # inner -> outer
        for i in range(n_rings - 1):
            a0, a1 = int(axis_idx[i]), int(axis_idx[i + 1])
            inner0, inner1 = shells[0][i], shells[0][i + 1]
            for j in range(m):
                jn = (j + 1) % m
                # prism (axis edge, inner ring quad) -> 3 tets
                p0, p1 = int(inner0[j]), int(inner0[jn])
                q0, q1 = int(inner1[j]), int(inner1[jn])
                tets.append((a0, p0, p1, a1))
                tets.append((a1, p0, p1, q1))
                tets.append((a1, p0, q1, q0))
            for k in range(len(shells) - 1):
                lo0, lo1 = shells[k][i], shells[k][i + 1]
                hi0, hi1 = shells[k + 1][i], shells[k + 1][i + 1]
                for j in range(m):
                    jn = (j + 1) % m
                    n0, n1 = int(lo0[j]), int(lo0[jn])
                    n2, n3 = int(lo1[jn]), int(lo1[j])
                    m0, m1 = int(hi0[j]), int(hi0[jn])
                    m2, m3 = int(hi1[jn]), int(hi1[j])
                    # hexahedron (n0 n1 n2 n3 / m0 m1 m2 m3) -> 6 tets on the
                    # n0-m2 diagonal
                    tets.append((n0, n1, n2, m2))
                    tets.append((n0, n2, n3, m2))
                    tets.append((n0, n1, m2, m1))
                    tets.append((n0, m1, m2, m0))
                    tets.append((n0, n3, m3, m2))
                    tets.append((n0, m3, m0, m2))
        tets = np.asarray(tets, dtype=int)

        p = self.rest[tets]
        dm = np.stack([p[:, 1] - p[:, 0], p[:, 2] - p[:, 0], p[:, 3] - p[:, 0]], axis=2)
        det = np.linalg.det(dm)
        # orient consistently and drop degenerate elements
        flip = det < 0.0
        if np.any(flip):
            tets[flip] = tets[flip][:, [0, 2, 1, 3]]
            p = self.rest[tets]
            dm = np.stack([p[:, 1] - p[:, 0], p[:, 2] - p[:, 0], p[:, 3] - p[:, 0]], axis=2)
            det = np.linalg.det(dm)
        keep = det > 1e-12
        self.tets = tets[keep]
        dm = dm[keep]
        self.volume = det[keep] / 6.0
        self.dm_inv = np.linalg.inv(dm)
        self.n_tets = len(self.tets)

        # ---- lumped mass --------------------------------------------------
        mass = np.zeros(self.n_nodes)
        share = self.density * self.volume / 4.0
        for c in range(4):
            mass += np.bincount(self.tets[:, c], weights=share, minlength=self.n_nodes)
        # the exported skin samples carry the frozen total flesh mass
        mass[:self.n_skin] = TOTAL_FLESH_MASS / self.n_skin
        self.mass = np.maximum(mass, 1.0e-3)
        self.inv_mass = 1.0 / self.mass
        self.skin_mass = self.mass[:self.n_skin].copy()

    def _build_attachments(self) -> None:
        hum = self.bones["humerus_bone"]
        fore = self.bones["forearm_bone"]
        d_h, _ = _segment_distance(self.rest, hum["a"], hum["b"])
        d_f, _ = _segment_distance(self.rest, fore["a"], fore["b"])
        margin = 0.004
        att_h = d_h <= hum["radius"] + margin
        att_f = d_f <= fore["radius"] + margin
        # terminal cross-sections are clamped to the bone they continue
        x = self.rest[:, 0]
        x_lo, x_hi = float(x.min()), float(x.max())
        att_h |= x <= x_lo + 1e-6
        att_f |= x >= x_hi - 1e-6
        # any node with no incident element carries no elastic force: clamp it
        incident = np.zeros(self.n_nodes, dtype=bool)
        incident[self.tets.reshape(-1)] = True
        orphan = ~incident
        att_h |= orphan & (x <= 0.0)
        att_f |= orphan & (x > 0.0)
        # a node inside both capsules near the joint follows the nearer bone
        both = att_h & att_f
        if np.any(both):
            take_f = d_f[both] < d_h[both]
            idx = np.where(both)[0]
            att_h[idx[take_f]] = False
            att_f[idx[~take_f]] = False
        self.att_h = np.where(att_h)[0]
        self.att_f = np.where(att_f)[0]
        self.free = np.where(~(att_h | att_f))[0]
        self.fore_offset = self.rest[self.att_f] - self.hinge_center
        pinned = np.zeros(self.n_nodes, dtype=bool)
        pinned[self.att_h] = True
        pinned[self.att_f] = True
        self.pinned = pinned
        self.skin_pinned_h = self.att_h[self.att_h < self.n_skin]
        self.skin_pinned_f = self.att_f[self.att_f < self.n_skin]

    def _build_contact_sets(self) -> None:
        """Candidate skin-skin pairs, excluding topologically adjacent rings."""
        ring_of = np.full(self.n_skin, -1, dtype=int)
        for i, ring in enumerate(self.ring_index):
            ring_of[ring] = i
        # end-cap centres inherit the ring id of their own cross-section
        for i, lev in enumerate(self.ring_levels):
            same = np.where(np.abs(self.skin_rest[:, 0] - lev) < 1e-6)[0]
            ring_of[same[ring_of[same] < 0]] = i
        iu, ju = np.triu_indices(self.n_skin, k=1)
        keep = np.abs(ring_of[iu] - ring_of[ju]) >= 2
        self._self_pairs = np.stack([iu[keep], ju[keep]], axis=1)
        self.ring_of = ring_of

    # ------------------------------------------------------------------ forces
    def _hinge_frame(self, t: float):
        angle, rate, accel = _hinge_state(
            t, self.t_start, self.t_end, self.angle0, self.angle1)
        R = _rotation(self.hinge_axis, angle)
        return R, self.hinge_axis * rate, self.hinge_axis * accel, angle

    def _apply_bc(self, t: float) -> None:
        R, omega, _alpha, _ang = self._hinge_frame(t)
        self.position[self.att_h] = self.rest[self.att_h]
        self.velocity[self.att_h] = 0.0
        rot = self.fore_offset @ R.T
        self.position[self.att_f] = self.hinge_center + rot
        self.velocity[self.att_f] = np.cross(omega, rot)

    def _internal_forces(self) -> np.ndarray:
        p = self.position[self.tets]
        v = self.velocity[self.tets]
        ds = np.stack([p[:, 1] - p[:, 0], p[:, 2] - p[:, 0], p[:, 3] - p[:, 0]], axis=2)
        F = ds @ self.dm_inv
        dv = np.stack([v[:, 1] - v[:, 0], v[:, 2] - v[:, 0], v[:, 3] - v[:, 0]], axis=2)
        Fdot = dv @ self.dm_inv

        f0, f1, f2 = F[:, :, 0], F[:, :, 1], F[:, :, 2]
        c0 = np.cross(f1, f2)
        c1 = np.cross(f2, f0)
        c2 = np.cross(f0, f1)
        dJ = np.stack([c0, c1, c2], axis=2)
        J = np.einsum("ij,ij->i", f0, c0)
        Ic = np.einsum("ijk,ijk->i", F, F)
        self._min_j = float(min(self._min_j, J.min()))
        self._max_j = float(max(self._max_j, J.max()))

        P = (self.mu * (1.0 - 1.0 / (Ic + 1.0)))[:, None, None] * F \
            + (self.lam * (J - self.alpha))[:, None, None] * dJ
        P = P + self.beta * Fdot

        H = -(self.volume[:, None, None]) * (P @ np.transpose(self.dm_inv, (0, 2, 1)))
        force = np.zeros((self.n_nodes, 3))
        for c in range(3):
            fc = H[:, :, c]
            for d in range(3):
                force[:, d] += np.bincount(self.tets[:, c + 1], weights=fc[:, d],
                                           minlength=self.n_nodes)
        total = H.sum(axis=2)
        for d in range(3):
            force[:, d] -= np.bincount(self.tets[:, 0], weights=total[:, d],
                                       minlength=self.n_nodes)
        self._last_F = F
        return force

    def _contact_forces(self, t: float) -> np.ndarray:
        force = np.zeros((self.n_nodes, 3))
        # --- skin self-contact ------------------------------------------
        pairs = self._broad_pairs
        if len(pairs):
            i, j = pairs[:, 0], pairs[:, 1]
            delta = self.position[i] - self.position[j]
            dist = np.sqrt(np.einsum("ij,ij->i", delta, delta))
            hit = dist < self.d_self
            if np.any(hit):
                i, j = i[hit], j[hit]
                delta = delta[hit]
                dist = np.maximum(dist[hit], 1e-9)
                n = delta / dist[:, None]
                pen = self.d_self - dist
                rel = np.einsum("ij,ij->i", self.velocity[i] - self.velocity[j], n)
                mag = self.k_self * pen - self.c_contact * rel
                mag = np.maximum(mag, 0.0)
                fvec = mag[:, None] * n
                for d in range(3):
                    force[:, d] += np.bincount(i, weights=fvec[:, d],
                                               minlength=self.n_nodes)
                    force[:, d] -= np.bincount(j, weights=fvec[:, d],
                                               minlength=self.n_nodes)
        # --- bone capsule contact ---------------------------------------
        R, omega, _a, _ang = self._hinge_frame(t)
        pts = self.position[self.free]
        vel = self.velocity[self.free]
        for name, bone in self.bones.items():
            if name == "forearm_bone":
                a = self.hinge_center + R @ (bone["a"] - self.hinge_center)
                b = self.hinge_center + R @ (bone["b"] - self.hinge_center)
            else:
                a, b = bone["a"], bone["b"]
            dist, delta = _segment_distance(pts, a, b)
            thick = bone["radius"] + 0.004
            hit = dist < thick
            if not np.any(hit):
                continue
            idx = self.free[hit]
            dsel = np.maximum(dist[hit], 1e-9)
            n = delta[hit] / dsel[:, None]
            pen = thick - dsel
            v_rel = vel[hit]
            if name == "forearm_bone":
                v_bone = np.cross(omega, self.position[idx] - self.hinge_center)
                v_rel = v_rel - v_bone
            rel = np.einsum("ij,ij->i", v_rel, n)
            mag = np.maximum(self.k_bone * pen - self.c_contact * rel, 0.0)
            fvec = mag[:, None] * n
            for d in range(3):
                force[:, d] += np.bincount(idx, weights=fvec[:, d],
                                           minlength=self.n_nodes)
        return force

    # ------------------------------------------------------------- integration
    def _refresh_broad_phase(self) -> None:
        pairs = self._self_pairs
        if not len(pairs):
            self._broad_pairs = pairs
            return
        delta = self.position[pairs[:, 0]] - self.position[pairs[:, 1]]
        dist = np.einsum("ij,ij->i", delta, delta)
        cut = (self.d_self + 0.05) ** 2
        self._broad_pairs = pairs[dist < cut]

    def _step(self, h: float) -> None:
        if self._broad_step % 10 == 0:
            self._refresh_broad_phase()
        self._broad_step += 1
        f_int = self._internal_forces()
        f_con = self._contact_forces(self.time)
        total = f_int + f_con + self.mass[:, None] * GRAVITY
        idx = self.free
        acc = total[idx] * self.inv_mass[idx, None]
        self.velocity[idx] += h * acc
        speed = np.linalg.norm(self.velocity[idx], axis=1)
        cap = 25.0
        hot = speed > cap
        if np.any(hot):
            scale = np.ones(len(idx))
            scale[hot] = cap / speed[hot]
            self.velocity[idx] *= scale[:, None]
        self.position[idx] += h * self.velocity[idx]
        self.time += h
        self._apply_bc(self.time)

    def advance_to(self, time: float) -> StateFrame:
        target = float(time)
        if target > self.time + 1e-12:
            span = target - self.time
            n = max(1, int(np.ceil(span / self.dt_max)))
            h = span / n
            for _ in range(n):
                self._step(h)
            self.time = target
            self._apply_bc(self.time)
        else:
            self._apply_bc(self.time)
        return self._frame(target)

    # ------------------------------------------------------------------ export
    def _frame(self, t: float) -> StateFrame:
        self._refresh_broad_phase()
        f_int = self._internal_forces()
        f_con = self._contact_forces(t)
        f_grav = self.mass[:, None] * GRAVITY

        n = self.n_skin
        grav_term = self.skin_mass.sum() * GRAVITY
        traction_term = f_int[:n].sum(axis=0)
        contact_term = f_con[:n].sum(axis=0)

        # reaction forces holding the kinematically driven skin samples
        _R, omega, alpha_vec, angle = self._hinge_frame(t)
        reaction = np.zeros(3)
        if len(self.skin_pinned_h):
            i = self.skin_pinned_h
            reaction -= (f_int[i] + f_con[i] + f_grav[i]).sum(axis=0)
        if len(self.skin_pinned_f):
            i = self.skin_pinned_f
            r = self.position[i] - self.hinge_center
            acc = np.cross(alpha_vec, r) + np.cross(omega, np.cross(omega, r))
            reaction += (self.mass[i, None] * acc
                         - (f_int[i] + f_con[i] + f_grav[i])).sum(axis=0)

        budget = np.zeros((1, 4, 3))
        budget[0, 0] = grav_term
        budget[0, 1] = traction_term
        budget[0, 2] = contact_term
        budget[0, 3] = reaction
        budget = np.nan_to_num(budget, nan=0.0, posinf=0.0, neginf=0.0)

        Fel = np.nan_to_num(np.ascontiguousarray(self._last_F, dtype=float),
                            nan=1.0, posinf=1.0, neginf=1.0)
        pos = np.nan_to_num(self.position[:n], nan=0.0, posinf=0.0, neginf=0.0)
        vel = np.nan_to_num(self.velocity[:n], nan=0.0, posinf=0.0, neginf=0.0)

        frame = StateFrame(
            time=float(t),
            position=pos.copy(),
            velocity=vel.copy(),
            mass=self.skin_mass.copy(),
            attributes={
                "mass_quantity": self.skin_mass.copy(),
                "rest_position": self.skin_rest.copy(),
            },
            fields={
                "element_deformation_gradient": Fel,
                "budget_external_force": budget,
                "budget_domain_weights": np.ones((1, n)),
                "cumulative_mass_source": np.zeros(1),
            },
            scalars={
                "reference_force": float(TOTAL_FLESH_MASS * 9.81),
                "elbow_flexion_degrees": float(np.rad2deg(angle)),
                "flesh_density_kg_m3": self.density,
            },
        )
        frame.validate()
        return frame

