"""Self-implemented quasi-static elastic-rod coiling solver (no external engine).

Physical model
--------------
One naturally straight, nearly inextensible elastic rod is fed downward through a
frozen injector outlet onto a rigid horizontal substrate under uniform gravity.
The rod is a polyline ``x_0 .. x_{n-1}``; node 0 is the material point at the
injector outlet, node ``n-1`` is the original free end already touching the
substrate.

Internal (conservative) energies, discretised on the polyline:

* axial    ``E_s = sum_j (EA / 2 L0_j) (|e_j| - L0_j)^2``
* bending  ``E_b = sum_p (EI / lbar_p) |t_p - t_{p-1}|^2 / 2``
  the standard discrete Kirchhoff bending energy of a naturally straight rod;
  ``|t_p - t_{p-1}|^2 = 2 (1 - cos theta_p)`` reproduces ``EI kappa^2 l / 2`` in
  the smooth limit.  Natural curvature is zero, as frozen by the config.

Boundary conditions and material feed:

* injector: node 0 is pinned at the frozen outlet, and the rod is *clamped* to
  the injector axis through a virtual upstream tangent ``t_-1 = axis``.  The
  clamp exerts a free couple, exported in ``fields.budget_external_couple``.
* injection: the rest length of the topmost edge grows at the frozen injection
  speed between ``ds`` and ``2 ds``, and the injected material is transported
  along the outlet tangent at ``v_inj``.  At ``2 ds`` the edge is split at its
  midpoint into two edges of rest length ``ds`` (adaptive material remeshing),
  so the deployed rest length is exactly ``L_init + v_inj * t`` at all times and
  no spurious axial compression is generated by the feed.
* substrate: rigid *sticking* condition.  A node reaching ``z = surface_z +
  radius`` is deposited and its position is frozen permanently (no sliding, no
  rebound).  Self-contact of deposited material is neglected, as in the source.

Time integration: semi-implicit (symplectic) Euler with the conservative
internal forces explicit and the external mass-proportional drag treated
implicitly.  Internal Rayleigh axial damping and pairwise edge viscosity damp
short-wavelength modes.  The drag places the rod in the source's quasi-static
regime (terminal speed g/cd is 30x the injection speed, so the drag force is a
few percent of gravity and does not distort statics).  The substep size keeps
the axial-wave mode well inside the stability limit of this scheme.
"""
from __future__ import annotations

import numpy as np

from worldsolver.contracts import StateFrame

_EPS = 1e-12


class BenchmarkSolver:
    # ------------------------------------------------------------------ setup
    def initialize(self, scene, seed: int) -> None:
        cfg = scene.config
        rod = cfg["rod"]
        inj = cfg["injector"]
        sub = cfg["substrate"]

        self.gvec = np.asarray(cfg["gravity"], dtype=float)
        self.radius = float(rod["radius"])
        self.rho = float(rod["density"])
        self.young = float(rod["young_modulus"])
        self.area = np.pi * self.radius ** 2
        self.second_moment = 0.25 * np.pi * self.radius ** 4
        self.EA = self.young * self.area
        self.EI = self.young * self.second_moment
        self.lin_mass = self.rho * self.area
        self.natural_curvature = float(rod.get("natural_curvature", 0.0))

        self.v_inj = float(inj["injection_speed"])
        self.t_start = float(inj["start_time"])
        self.t_end = float(inj["end_time"])
        self.outlet = np.asarray(inj["outlet_position"], dtype=float)
        axis = np.asarray(inj["axis"], dtype=float)
        anorm = float(np.linalg.norm(axis))
        self.axis = axis / anorm if anorm > _EPS else np.array([0.0, 0.0, -1.0])

        self.surface_z = float(sub["surface_z"])
        self.zc = self.surface_z + self.radius

        self.L_init = float(rod["initial_deployed_length"])
        self.L_max = float(rod["total_available_length"])
        self.fed_max = max(self.L_max - self.L_init, 0.0)

        # ---- frozen initial geometry, resampled to solver resolution
        frame0 = scene.initial_state()
        p0 = np.asarray(frame0.position, dtype=float)
        arc0 = np.asarray(frame0.attributes["arc_coordinate"], dtype=float)

        nseg = max(int(round(self.L_init / 0.0125)), 4)
        self.ds = self.L_init / nseg
        arc = np.linspace(0.0, self.L_init, nseg + 1)
        n = nseg + 1
        x = np.empty((n, 3), dtype=float)
        for k in range(3):
            x[:, k] = np.interp(arc, arc0, p0[:, k])
        x[0] = self.outlet
        x[-1] = p0[-1]

        # Deterministic out-of-plane imperfection.  The frozen symmetry break in
        # the asset lies entirely in the x-z plane; with exactly planar geometry
        # and planar loading the discrete equations preserve that plane forever
        # and the heel would fold instead of coil.  A physical rod always carries
        # a small out-of-plane imperfection, so a coherent lateral bow (0.2 mm,
        # about 1/8 of the frozen in-plane offset) plus a seeded micro-noise is
        # applied.  This selects a definite chirality; it prescribes no motion.
        rng = np.random.default_rng(int(seed))
        kernel = np.array([1.0, 2.0, 3.0, 2.0, 1.0])
        kernel /= kernel.sum()
        noise = np.convolve(rng.standard_normal(n), kernel, mode="same")
        window = np.sin(np.pi * np.arange(n) / (n - 1))
        x[:, 1] += window * (2.0e-4 + 2.0e-5 * noise)

        self.x = np.ascontiguousarray(x)
        self.v = np.zeros_like(self.x)
        self.n = n
        self.L0 = np.full(n - 1, self.ds, dtype=float)
        self.nsplit = 0
        self.fed = 0.0
        self.nmax = int(self.L_max / self.ds) + 6
        self.feed_vec = np.zeros(3, dtype=float)

        # sticking substrate + injector clamp: prescribed (frozen) nodes
        self.fixed = np.zeros(n, dtype=bool)
        self.fixed[0] = True
        self.x[self.x[:, 2] < self.zc, 2] = self.zc
        self.fixed[self.x[:, 2] <= self.zc + 1e-12] = True
        self.target = self.x.copy()
        self.m = np.empty(n, dtype=float)
        self._recompute_mass()

        # ---- numerical parameters
        self.alpha = 4.0e-5      # internal Rayleigh axial damping time (s)
        self.mu = 0.04           # internal pairwise edge viscosity (N*s/m)
        self.cd = 60.0           # external drag rate (1/s) -> quasi-static
        self.substeps = 150
        self.dt = float(cfg["sample_dt"]) / self.substeps
        self.t = 0.0
        self.step_count = 0

        self.ref_force = float(self.lin_mass * self.L_max * abs(self.gvec[2]))
        if not (self.ref_force > 0.0):
            self.ref_force = 1.0
        self.ref_torque = float(self.ref_force * self.L_init)
        if not (self.ref_torque > 0.0):
            self.ref_torque = 1.0
        self.constraint_scale = float(self.radius)

    # ------------------------------------------------------------- internals
    def _recompute_mass(self) -> None:
        L0 = self.L0
        voronoi = np.empty(self.n, dtype=float)
        voronoi[0] = 0.5 * L0[0]
        voronoi[-1] = 0.5 * L0[-1]
        if self.n > 2:
            voronoi[1:-1] = 0.5 * (L0[:-1] + L0[1:])
        self.m = self.lin_mass * voronoi

    def _split_top_edge(self) -> None:
        """Insert one material node at the midpoint of the growing top edge."""
        xm = 0.5 * (self.x[0] + self.x[1])
        vm = 0.5 * (self.v[0] + self.v[1])
        self.x = np.insert(self.x, 1, xm, axis=0)
        self.v = np.insert(self.v, 1, vm, axis=0)
        self.target = np.insert(self.target, 1, xm, axis=0)
        self.fixed = np.insert(self.fixed, 1, False)
        self.L0 = np.concatenate((np.array([self.ds, self.ds]), self.L0[1:]))
        self.n += 1
        self.nsplit += 1
        self._recompute_mass()

    def _internal_force(self, x, v, damping: bool = True):
        """Discrete elastic rod forces: axial + bending (+ internal damping)."""
        L0 = self.L0
        e = x[1:] - x[:-1]
        el = np.sqrt(np.einsum("ij,ij->i", e, e))
        np.maximum(el, _EPS, out=el)
        t = e / el[:, None]

        # axial: gradient with respect to each edge vector
        axial = self.EA * (el - L0) / L0
        if damping:
            rate = np.einsum("ij,ij->i", v[1:] - v[:-1], t)
            axial = axial + (self.EA * self.alpha / L0) * rate
        grad = axial[:, None] * t

        # bending with a virtual upstream tangent enforcing the injector clamp
        ne = el.shape[0]
        T = np.empty((ne + 1, 3), dtype=float)
        T[0] = self.axis
        T[1:] = t
        EL = np.empty(ne + 1, dtype=float)
        EL[0] = self.ds
        EL[1:] = el
        RS = np.empty(ne + 1, dtype=float)
        RS[0] = self.ds
        RS[1:] = L0
        Tp = T[1:]
        Tm = T[:-1]
        u = Tp - Tm
        kb = self.EI / (0.5 * (RS[:-1] + RS[1:]))
        # d/dx of |t_p - t_{p-1}|^2 projected off each unit tangent
        A = (kb / EL[1:])[:, None] * (u - np.einsum("ij,ij->i", u, Tp)[:, None] * Tp)
        B = (kb / EL[:-1])[:, None] * (u - np.einsum("ij,ij->i", u, Tm)[:, None] * Tm)
        grad += A
        grad[:-1] -= B[1:]

        force = np.zeros_like(x)
        force[:-1] += grad
        force[1:] -= grad

        if damping and self.mu > 0.0:
            fd = self.mu * (v[1:] - v[:-1])
            force[:-1] += fd
            force[1:] -= fd
        return force

    def _step(self, dt: float, tnow: float) -> None:
        # prescribed feed: deployed rest length is exactly L_init + v_inj * t
        span = min(max(tnow - self.t_start, 0.0), max(self.t_end - self.t_start, 0.0))
        fed = min(self.v_inj * span, self.fed_max)
        self.fed = fed
        while (fed - self.nsplit * self.ds) >= self.ds and self.n < self.nmax:
            self._split_top_edge()
        self.L0[0] = self.ds + (fed - self.nsplit * self.ds)
        self.m[0] = 0.5 * self.lin_mass * self.L0[0]
        if self.n > 2:
            self.m[1] = 0.5 * self.lin_mass * (self.L0[0] + self.L0[1])

        # material transport of the injected node along the outlet tangent
        self.feed_vec[:] = 0.0
        if fed < self.fed_max - 1e-15 and tnow >= self.t_start and not self.fixed[1]:
            d = self.x[1] - self.x[0]
            dn = float(np.linalg.norm(d))
            if dn > _EPS:
                self.feed_vec[:] = self.v_inj * (d / dn)

        force = self._internal_force(self.x, self.v)
        force += self.m[:, None] * self.gvec
        vn = (self.v + dt * (force / self.m[:, None])) / (1.0 + dt * self.cd)
        vn[self.fixed] = 0.0
        self.v = vn
        self.x += dt * vn
        self.x[1] += dt * self.feed_vec
        self.x[0] = self.outlet

        # rigid sticking substrate: deposited nodes are frozen permanently
        landed = (self.x[:, 2] <= self.zc) & (~self.fixed)
        if landed.any():
            idx = np.flatnonzero(landed)
            self.x[idx, 2] = self.zc
            self.v[idx] = 0.0
            self.fixed[idx] = True
            self.target[idx] = self.x[idx]
        self.step_count += 1

    # ---------------------------------------------------------------- output
    def _material_frames(self, x, v):
        """Unit tangents as quaternions (identity at t=0) and their spin rates."""
        n = x.shape[0]
        d = np.empty((n, 3), dtype=float)
        d[1:-1] = x[2:] - x[:-2]
        d[0] = x[1] - x[0]
        d[-1] = x[-1] - x[-2]
        dl = np.sqrt(np.einsum("ij,ij->i", d, d))
        np.maximum(dl, _EPS, out=dl)
        d /= dl[:, None]

        rdot = np.empty((n, 3), dtype=float)
        rdot[1:-1] = v[2:] - v[:-2]
        rdot[0] = v[1] - v[0]
        rdot[-1] = v[-1] - v[-2]
        along = np.einsum("ij,ij->i", rdot, d)
        ddot = (rdot - along[:, None] * d) / dl[:, None]
        omega = np.cross(d, ddot)

        ref = self.axis
        quat = np.empty((n, 4), dtype=float)
        quat[:, :3] = np.cross(np.broadcast_to(ref, d.shape), d)
        quat[:, 3] = 1.0 + d @ ref
        qn = np.sqrt(np.einsum("ij,ij->i", quat, quat))
        bad = qn < 1e-9
        if bad.any():
            perp = np.cross(ref, np.array([1.0, 0.0, 0.0]))
            if np.linalg.norm(perp) < 1e-9:
                perp = np.cross(ref, np.array([0.0, 1.0, 0.0]))
            perp = perp / np.linalg.norm(perp)
            quat[bad, :3] = perp
            quat[bad, 3] = 0.0
            qn = np.sqrt(np.einsum("ij,ij->i", quat, quat))
        quat /= qn[:, None]
        return quat, omega

    def _frame(self, time: float) -> StateFrame:
        n = self.n
        x = self.x.copy()
        v = self.v.copy()
        v[1] += self.feed_vec  # material velocity of the injected node
        m = self.m.copy()

        f_int = self._internal_force(self.x, self.v, damping=True)
        f_elastic = self._internal_force(self.x, self.v, damping=False)
        f_grav = m[:, None] * self.gvec
        f_drag = -self.cd * m[:, None] * self.v
        f_drag[self.fixed] = 0.0

        # external constraint reactions: prescribed nodes (injector clamp node
        # and deposited sticking nodes) carry zero acceleration.
        reaction = np.zeros((n, 3), dtype=float)
        fx = self.fixed
        reaction[fx] = -(f_int[fx] + f_grav[fx] + f_drag[fx])

        k = 3 * n
        b_force = np.empty((1, k, 3), dtype=float)
        b_force[0, 0:n] = f_grav
        b_force[0, n:2 * n] = f_drag
        b_force[0, 2 * n:3 * n] = reaction
        b_pos = np.empty((1, k, 3), dtype=float)
        b_pos[0, 0:n] = x
        b_pos[0, n:2 * n] = x
        b_pos[0, 2 * n:3 * n] = x
        b_couple = np.zeros((1, k, 3), dtype=float)
        # The clamp is the only free couple: the conservative internal force
        # field is translation invariant (zero net force) but not rotation
        # invariant about the clamped tangent, so its residual net torque is
        # exactly the couple applied by the injector clamp.
        b_couple[0, 0] = np.cross(x, f_elastic).sum(axis=0)

        # constraint: prescribed nodes must stay at their frozen targets
        # (injector-controlled node 0 and sticking deposited nodes).
        c_target = np.where(fx[:, None], self.target, x)

        arc = np.empty(n, dtype=float)
        arc[0] = 0.0
        np.cumsum(self.L0, out=arc[1:])

        quat, omega = self._material_frames(x, self.v)

        frame = StateFrame(
            time=float(time),
            position=x,
            velocity=v,
            orientation=quat,
            angular_velocity=omega,
            mass=m,
            body_id=np.zeros(n, dtype=np.int64),
            attributes={
                "arc_coordinate": arc,
                "is_injector_controlled": (np.arange(n) == 0).astype(float),
                "is_initial_contact": (np.arange(n) == n - 1).astype(float),
                "is_deposited": fx.astype(float),
                "rod_radius": np.full(n, self.radius),
                "mass_quantity": m,
            },
            fields={
                "budget_external_force": b_force,
                "budget_force_position": b_pos,
                "budget_external_couple": b_couple,
                "constraint_value": x,
                "constraint_target": c_target,
                "cumulative_mass_source": np.array(
                    [self.lin_mass * self.fed], dtype=float
                ),
            },
            scalars={
                "constraint_scale": self.constraint_scale,
                "reference_force": self.ref_force,
                "reference_torque": self.ref_torque,
                "injection_speed": float(self.v_inj),
                "natural_curvature": float(self.natural_curvature),
                "substrate_speed": 0.0,
                "deployed_length": float(self.L_init + self.fed),
                "deposited_node_count": float(int(fx.sum())),
                "node_count": float(n),
            },
        )
        frame.validate()
        return frame

    # -------------------------------------------------------------- contract
    def advance_to(self, time: float) -> StateFrame:
        target = float(time)
        if target > self.t + 1e-15:
            steps = max(int(np.ceil((target - self.t) / self.dt - 1e-9)), 1)
            dt = (target - self.t) / steps
            for _ in range(steps):
                self.t += dt
                self._step(dt, self.t)
            self.t = target
        return self._frame(target)

    def diagnostics(self) -> dict[str, object]:
        return {
            "model": "discrete elastic rod (axial + bending), clamped injector, "
                     "rigid sticking substrate, no self-contact",
            "integrator": "semi-implicit Euler, implicit mass-proportional drag",
            "segment_rest_length": float(self.ds),
            "substep_dt": float(self.dt),
            "steps_taken": int(self.step_count),
            "final_node_count": int(self.n),
            "final_deployed_length": float(self.L_init + self.fed),
            "deposited_nodes": int(self.fixed.sum()),
            "gravito_bending_length": float(
                (self.EI / (self.lin_mass * abs(self.gvec[2]))) ** (1.0 / 3.0)
            ),
        }
